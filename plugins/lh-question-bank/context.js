/**
 * 注入给模型的**运行时上下文**：刷题这件事该怎么走。
 *
 * ═══ 为什么需要它（一次实测的产物，不是设计偏好）═══
 * 2026-09-19 晚上，学习者说"按知识点出题"，agent 调了 `get_questions`
 * （工具调用的记录在 `data/events.jsonl` 的 `lh/trace/observed` 里，共 2 次），
 * **一次都没调 `start_practice`** —— 于是对话里没有卡片，题被念在文本里，
 * 做完也留不下作答记录。
 *
 * 而 `get_questions` 的描述里**已经写了**一段"什么时候不要用它"（那是上一次同类事故后补的），
 * 里面明说"学习者说要刷题时一律调 `start_practice`"。**它仍然没被遵守。**
 *
 * → 所以这条规则不能只放在**某一个工具的**描述里，要放在**每次组装都会出现**的上下文里：
 *   工具描述是"用到那个工具时才读到的"，而运行时上下文在**计划阶段**就在。
 *   这与 ADR-016 决定 2 是同一条理由：
 *   *"让 agent 在计划时就知道，而不是等动工之后才发现。"*
 *
 * ═══ 措辞纪律 ═══
 * - **陈述事实与后果，不下命令**（同 `lh-model-tier` 的档位上下文）；
 * - **每条新名词当场解释**（WORKFLOW §4 义务 6）；
 * - **越短越好**：这段每次组装都要占用 token，而它要说的事只有一件。
 *   所以它不重复词表清单（那在工具描述里），只讲**两条路的分工与后果**。
 */

/**
 * 渲染这段上下文。
 *
 * @returns 供模型读的文本。
 */
export function renderPracticeRoutingContext() {
  return [
    '刷题这件事有两条路，走错的那条**做完留不下记录**：',
    '- **进入刷题**（"刷题 / 继续刷题 / 给我 N 题 / 重刷做过的 / 只练错题 / 按某个知识点出题"）→ 调 `start_practice`：',
    '  它会在对话里放一张卡片，学习者点它打开面板；**题在面板里作答**，每次作答都会被判分并写进 LH 事件日志（于是有进度、有错题本）。',
    '- **就在对话里问一道题**（学习者明说"问我一道"、或你想顺口考他一下）→ 调 `get_questions`：',
    '  它把题交给你念出来，**不写事件日志**，所以那条路没有进度、没有错题本，也别指望事后能统计。',
    '**判据是学习者想要哪一件事，不是哪个工具更顺手。**若他要的是"练"，就把选择（题库、知识点、题数、顺序）通过 `start_practice` 的参数传进去。',
    '另外：`start_practice` 返回的 `selection_applied` 是这次卡片代表的选择，**务必照它向学习者复述一遍**，否则他无法确认你说的是不是他要的。',
  ].join('\n')
}
